set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TERRAFORM_DIR="${SCRIPT_DIR}/terraform"
ANSIBLE_DIR="${SCRIPT_DIR}/ansible"

echo "=========================================================="
echo " Starting DevOps Environment Cleanup & Destruction"
echo "=========================================================="

# 1. Destroy AWS Cloud Infrastructure via Terraform
if [ -d "${TERRAFORM_DIR}" ]; then
    echo "[+] Running 'terraform destroy' to terminate AWS EC2 resources..."
    cd "${TERRAFORM_DIR}"
    if [ -f "terraform.tfstate" ]; then
        terraform destroy -auto-approve || echo "[!] Terraform destroy encountered an error, continuing file cleanup..."
    else
        echo "[-] No terraform.tfstate found. Skipping terraform destroy."
    fi
fi

# 2. Clean up runtime generated files
echo "[+] Cleaning up local runtime-generated files..."

# Remove private SSH key generated by Terraform
if [ -f "${SCRIPT_DIR}/id_rsa" ]; then
    echo "  - Removing ${SCRIPT_DIR}/id_rsa"
    rm -f "${SCRIPT_DIR}/id_rsa"
fi

# Remove dynamically generated Ansible inventory
if [ -f "${ANSIBLE_DIR}/inventory.ini" ]; then
    echo "  - Removing ${ANSIBLE_DIR}/inventory.ini"
    rm -f "${ANSIBLE_DIR}/inventory.ini"
fi

# Remove Terraform state and plan files
if [ -d "${TERRAFORM_DIR}" ]; then
    echo "  - Cleaning Terraform state and plan artifacts..."
    rm -f "${TERRAFORM_DIR}/terraform.tfstate"*
    rm -f "${TERRAFORM_DIR}/tfplan"*
    rm -f "${TERRAFORM_DIR}/.terraform.tfstate"*
fi

# Optional: clean up Ansible retry files if present
rm -f "${ANSIBLE_DIR}"/*.retry 2>/dev/null || true

echo "=========================================================="
echo " Cleanup Complete!"
echo " - AWS EC2 instance terminated"
echo " - Security groups and key pairs deleted"
echo " - Runtime files (id_rsa, inventory.ini, state) wiped"
echo " - Working tree restored to clean Git source state"
echo "=========================================================="
